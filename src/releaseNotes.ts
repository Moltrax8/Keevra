/**
 * Release-note parser for the update dialog (pure, testable).
 *
 * GitHub releases carry the CHANGELOG section as Markdown. The dialog renders
 * a structured, sectional card instead of a wall of text, so the body is
 * reduced to:
 *
 *   headline  — one bold line (or the first heading) at the top
 *   intro     — the leading paragraph(s)
 *   sections  — `### Heading` blocks, each with bullet items
 *
 * A bullet that begins with `**Title.**` becomes a titled item; any other
 * prose line is kept as an untitled item. The parser never throws; unknown
 * shapes fall back to a single "Other Changes" section.
 */

export type ReleaseNoteKind =
  | "features"
  | "improvements"
  | "fixes"
  | "security"
  | "notes"
  | "technical"
  | "other";

export interface ReleaseNoteItem {
  title: string | null;
  body: string;
}

export interface ReleaseNoteSection {
  kind: ReleaseNoteKind;
  label: string;
  emoji: string;
  items: ReleaseNoteItem[];
}

export interface ParsedReleaseNotes {
  headline: string;
  intro: string;
  sections: ReleaseNoteSection[];
}

/** Display metadata per section kind, ordered roughly as releases read. */
export const SECTION_META: Record<ReleaseNoteKind, { label: string; emoji: string }> = {
  features: { label: "New Features", emoji: "✨" },
  improvements: { label: "Improvements", emoji: "⚡" },
  fixes: { label: "Bug Fixes", emoji: "🐞" },
  security: { label: "Security", emoji: "🔐" },
  notes: { label: "Important Notes", emoji: "📌" },
  technical: { label: "Tests & Internals", emoji: "🧪" },
  other: { label: "Other Changes", emoji: "📝" },
};

const KIND_PATTERNS: ReadonlyArray<readonly [ReleaseNoteKind, RegExp]> = [
  ["security", /secur|privacy|hardening|vulnerab/],
  ["features", /new|feature|added|introduc/],
  ["improvements", /improv|enhanc|performance|polish|change|updated/],
  ["fixes", /fix|bug|resolved|correct/],
  ["technical", /test|technical|internal|build|refactor|chore|\bci\b/],
  ["notes", /note|breaking|known|migration|compat|requirement|action/],
];

/** Section kind for a Markdown heading, defaulting to `other`. */
export function classifySection(title: string): ReleaseNoteKind {
  const haystack = title.toLowerCase();
  for (const [kind, pattern] of KIND_PATTERNS) {
    if (pattern.test(haystack)) return kind;
  }
  return "other";
}

/** A paragraph generated by the release workflow rather than the changelog. */
const WORKFLOW_NOTICE = /^(unsigned build|draft\.)/i;

const BOLD_LINE = /^\*\*(.+?)\*\*[.:]?\s*(.*)$/;
const BULLET = /^\s*[-*+]\s+(.*)$/;
const HEADING = /^\s*#{1,6}\s+(.*)$/;

const VERSION_BOLD = /^\*\*v?(\d+(?:\.\d+)*)[^*]*\*\*/;

function section(kind: ReleaseNoteKind, items: ReleaseNoteItem[] = []): ReleaseNoteSection {
  const meta = SECTION_META[kind];
  return { kind, label: meta.label, emoji: meta.emoji, items };
}

function pushParagraph(sections: ReleaseNoteSection[], kind: ReleaseNoteKind, text: string) {
  let target = sections.find((candidate) => candidate.kind === kind);
  if (!target) {
    target = section(kind);
    sections.push(target);
  }
  target.items.push({ title: null, body: text });
}

function parseItem(text: string): ReleaseNoteItem {
  const match = BOLD_LINE.exec(text);
  if (match) {
    const body = match[2]?.trim() ?? "";
    return { title: match[1].trim().replace(/[.:]$/, ""), body };
  }
  return { title: null, body: text };
}

/**
 * Splits `body` into blocks of `{ heading, lines }`, where `heading` is the
 * text of the last `###`/`##` heading and `lines` are the lines under it.
 */
function splitBlocks(body: string): Array<{ heading: string | null; lines: string[] }> {
  const blocks: Array<{ heading: string | null; lines: string[] }> = [{ heading: null, lines: [] }];
  for (const raw of body.replace(/\r\n?/g, "\n").split("\n")) {
    const heading = HEADING.exec(raw);
    if (heading) {
      blocks.push({ heading: heading[1].trim(), lines: [] });
      continue;
    }
    blocks[blocks.length - 1].lines.push(raw);
  }
  return blocks;
}

/** Collapses blank-line-separated prose into paragraphs. */
function paragraphs(lines: string[]): string[] {
  const out: string[] = [];
  let buffer: string[] = [];
  for (const line of lines) {
    if (line.trim() === "") {
      if (buffer.length > 0) {
        out.push(buffer.join(" ").trim());
        buffer = [];
      }
    } else {
      buffer.push(line.trim());
    }
  }
  if (buffer.length > 0) out.push(buffer.join(" ").trim());
  return out.filter((text) => text !== "");
}

/** Parses bullets (with continuation lines) out of a section's lines. */
function parseBullets(lines: string[]): ReleaseNoteItem[] {
  const items: ReleaseNoteItem[] = [];
  let current: string[] | null = null;
  let loose: string[] = [];

  const flushLoose = () => {
    if (loose.length > 0) {
      items.push({ title: null, body: loose.join(" ").trim() });
      loose = [];
    }
  };
  const flushItem = () => {
    if (current) {
      items.push(parseItem(current.join(" ").trim()));
      current = null;
    }
  };

  for (const raw of lines) {
    const bullet = BULLET.exec(raw);
    if (bullet) {
      flushItem();
      flushLoose();
      current = [bullet[1].trim()];
      continue;
    }
    if (raw.trim() === "") {
      flushItem();
      flushLoose();
      continue;
    }
    if (current) current.push(raw.trim());
    else loose.push(raw.trim());
  }
  flushItem();
  flushLoose();
  return items.filter((item) => item.title !== null || item.body !== "");
}

/**
 * Parses a release body. `tag` seeds the fallback headline ("What's new in
 * 0.2.2") when the body has no bold headline line.
 */
export function parseReleaseNotes(body: string | null | undefined, tag = ""): ParsedReleaseNotes {
  const text = (body ?? "").trim();
  const prettyTag = tag.trim().replace(/^v/i, "");
  const fallbackHeadline = prettyTag ? `What’s new in ${prettyTag}` : "What’s new";

  if (text === "") {
    return { headline: fallbackHeadline, intro: "", sections: [] };
  }

  const blocks = splitBlocks(text);
  const sections: ReleaseNoteSection[] = [];
  const intro: string[] = [];
  let headline = "";

  for (const [index, block] of blocks.entries()) {
    if (block.heading) {
      const kind = classifySection(block.heading);
      const items = parseBullets(block.lines);
      if (items.length > 0) {
        const existing = sections.find((candidate) => candidate.kind === kind);
        if (existing) existing.items.push(...items);
        else sections.push(section(kind, items));
      }
      continue;
    }

    for (const paragraph of paragraphs(block.lines)) {
      if (WORKFLOW_NOTICE.test(paragraph)) {
        // Render the workflow's unsigned/draft warning as an actionable note.
        const cleaned = paragraph.replace(/\s*See docs\/[^\s.]+\.?/gi, "").trim();
        pushParagraph(sections, "notes", cleaned === "" ? paragraph : cleaned);
        continue;
      }

      const bold = BOLD_LINE.exec(paragraph);
      if (!headline && bold && bold[2]?.trim()) {
        headline = bold[1].trim();
        intro.push(bold[2].trim());
        continue;
      }
      if (!headline && bold && !bold[2]?.trim()) {
        headline = bold[1].trim();
        continue;
      }
      intro.push(paragraph);
    }

    // A version banner such as "**v0.2.2**" is a heading, not prose.
    if (index === 0 && !headline) {
      const banner = VERSION_BOLD.exec(intro[0] ?? "");
      if (banner) {
        headline = intro.shift() ?? "";
        headline = headline.replace(VERSION_BOLD, (whole) => whole.replace(/\*/g, "")).trim();
      }
    }
  }

  // Keep notes (workflow warnings) first: they are the "read me first" item.
  sections.sort((a, b) => (a.kind === "notes" ? -1 : b.kind === "notes" ? 1 : 0));

  return { headline: headline || fallbackHeadline, intro: intro.join(" ").trim(), sections };
}

/** "2026-11-07T15:30:12Z" -> "November 7, 2026" (empty when unparseable). */
export function formatReleaseDate(publishedAt?: string | null): string {
  if (!publishedAt) return "";
  const date = new Date(publishedAt);
  if (Number.isNaN(date.getTime())) return "";
  return date.toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" });
}
